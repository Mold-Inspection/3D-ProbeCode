import cadquery as cq

# ==========================================
# 1. กำหนดขนาดของแม่แบบ (Parameters)
# ==========================================
mold_width = 100.0   # ความกว้างแม่แบบ (มม.)
mold_length = 150.0  # ความยาวแม่แบบ (มม.)
mold_thickness = 30.0 # ความหนาแม่แบบ (มม.)

# รูที่ 1 (รูใหญ่ - Big Guide Hole) อยู่ฝั่งซ้าย
hole_1_radius = 12.0  # เส้นผ่านศูนย์กลาง 24 มม.
hole_1_x = -35.0      # ตำแหน่งแกน X
hole_1_y = 0.0        # ตำแหน่งแกน Y

# รูที่ 2 (รูเล็ก - Small Guide Hole) อยู่ฝั่งขวา เพื่อป้องกันการหลงทิศ
hole_2_radius = 6.0   # เส้นผ่านศูนย์กลาง 12 มม. (ต่างกัน 2 เท่าให้เห็นชัดๆ)
hole_2_x = 35.0       # ตำแหน่งแกน X
hole_2_y = 0.0        # ตำแหน่งแกน Y

# ==========================================
# 2. เริ่มสร้างโมเดล 3 มิติ
# ==========================================

# สร้างก้อนแม่แบบสี่เหลี่ยม (Block) จากจุดศูนย์กลาง
mold = cq.Workplane("XY").box(mold_width, mold_length, mold_thickness)

# เจาะรูที่ 1 (รูใหญ่) ทะลุผ่านชิ้นงาน (Through Hole)
mold = (mold.faces(">Z") # เลือกพื้นผิวด้านบนสุด
        .workplane()     # สร้างระนาบทำงานบนผิวเสมือน
        .center(hole_1_x, hole_1_y) # ย้ายจุดศูนย์กลางไปตำแหน่งรูที่ 1
        .hole(hole_1_radius * 2))   # ฟังก์ชัน .hole() ใช้ค่า เส้นผ่านศูนย์กลาง (Diameter)

# เจาะรูที่ 2 (รูเล็ก) ทะลุผ่านชิ้นงาน
mold = (mold.faces(">Z") 
        .workplane()
        .center(hole_2_x, hole_2_y) # ย้ายจุดศูนย์กลางไปตำแหน่งรูที่ 2
        .hole(hole_2_radius * 2))

# ==========================================
# 3. ส่งออกไฟล์ (Export) เป็นนามสกุล STEP
# ==========================================
output_filename = "mold_base_poka_yoke.step"
cq.exporters.export(mold, output_filename)

print(f"สร้างโมเดลแม่แบบ 3 มิติสำเร็จแล้ว! ไฟล์ถูกบันทึกในชื่อ: {output_filename}")