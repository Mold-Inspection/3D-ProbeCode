import cadquery as cq

def create_test_part():
    print("กำลังสร้างชิ้นงานทดสอบ 3 มิติ...")
    
    # สร้างบล็อกพื้นฐานขนาด กว้าง 100 x ยาว 50 x หนา 20 mm
    base = cq.Workplane("XY").box(100, 50, 20)
    
    # ---------------------------------------------------------
    # รูที่ 1 (ฝั่งซ้าย): ทดสอบ _MAX_RADIUS_RATIO (ที่ตั้งไว้ 1.2)
    # ---------------------------------------------------------
    # สร้าง Counterbore มาตรฐาน M6
    # รัศมีรูทะลุ = 3.25 (Dia 6.5)
    # รัศมีหัวคว้าน = 5.5 (Dia 11.0) ลึก 6.0
    # อัตราส่วน = 5.5 / 3.25 = 1.69 
    # **สิ่งที่ควรเกิดใน Log:** ถ้าระบบตั้งไว้ 1.2 รูนี้จะต้องโดน "REJECTED (radius ratio ...)" แน่นอน
    base = base.faces(">Z").workplane().pushPoints([(-30, 0)]).cboreHole(diameter=6.5, cboreDiameter=11.0, cboreDepth=6.0)
    
    # ---------------------------------------------------------
    # รูที่ 2 (ตรงกลาง): ทดสอบ _COAXIAL_GAP_TOL (ที่ตั้งไว้ 5.0mm)
    # ---------------------------------------------------------
    # เจาะรูตันด้านบนลึก 8mm และด้านล่างลึก 8mm (แกนตรงกันเป๊ะ)
    # ความหนาชิ้นงาน 20mm ลบ รูบน 8mm ลบ รูล่าง 8mm = เหลือเนื้อตรงกลาง (Gap) 4mm
    # **สิ่งที่ควรเกิดใน Log:** ถ้าระบบตั้ง Gap Tol = 5.0 รู 2 รูนี้จะถูกดึงไปรวมกันเป็นรูทะลุรูเดียว (False Merge)
    base = base.faces(">Z").workplane().pushPoints([(0, 0)]).hole(diameter=6.0, depth=8.0)
    base = base.faces("<Z").workplane().pushPoints([(0, 0)]).hole(diameter=6.0, depth=8.0)

    # ---------------------------------------------------------
    # รูที่ 3 (ฝั่งขวา): ทดสอบ _AXIS_TOL (ที่ตั้งไว้ 0.02 หรือ ~11.5 องศา)
    # ---------------------------------------------------------
    # เจาะรูทะลุ แต่เอียงทำมุม 8 องศาจากแนวแกน Z
    # **สิ่งที่ควรเกิดใน Log:** ถ้าระบบหลวมเกินไป มันอาจจะยอมให้รูนี้มีแกนเดียวกับรูในแนวตั้งฉากปกติ
    tilted_hole = (
        cq.Workplane("XY")
        .transformed(offset=cq.Vector(30, 0, 0), rotate=cq.Vector(0, 8, 0))
        .circle(3.0)
        .extrude(50, both=True)
    )
    base = base.cut(tilted_hole)

    # ---------------------------------------------------------
    # ส่งออกเป็นไฟล์ STEP
    # ---------------------------------------------------------
    file_name = "test_tolerances.step"
    cq.exporters.export(base, file_name)
    print(f"เสร็จสิ้น! สร้างไฟล์ '{file_name}' เรียบร้อยแล้ว")
    print("นำไฟล์นี้ไปโยนเข้า script ของคุณพร้อมเปิด DEBUG=True ได้เลยครับ")

if __name__ == "__main__":
    create_test_part()