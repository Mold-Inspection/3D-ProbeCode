import cadquery as cq

print("กำลังสร้างโมเดลแม่พิมพ์แบบผ่าครึ่ง (Half-Mold Block)...")

# 1. สร้างก้อนแม่พิมพ์ "ครึ่งเดียว" (Half Block)
# ขนาด กว้าง(X) 60 มม. ลึก(Y) 30 มม. สูง(Z) 22 มม.
# การให้ centered=(True, False) ในแนว XY จะทำให้ขอบชิ้นงานอยู่ที่ระนาบ Y=0 พอดี
# ทำให้เกิดผิวหน้าเรียบแบนสนิทสำหรับวางแนบกับเครื่องวัด
mold = cq.Workplane("XY").rect(60, 30, centered=(True, False)).extrude(22)

# 2. ร่างเส้นขอบหลุมแก้ว (Profile) บนระนาบ XZ
# ผิวด้านข้างจะถูกวาดเป็นเส้นตรง (Straight Draft) เพื่อให้วัดมุมหรือระยะได้ง่าย
cavity_profile = (
    cq.Workplane("XZ")
    .moveTo(0, 2)       # จุดเริ่มที่แกนกลาง ก้นหลุม (สูงจากพื้น 2 มม. เพื่อเหลือเนื้อฐาน)
    .lineTo(12, 2)      # ลากออกไป 12 มม. (รัศมีก้นแก้ว)
    .lineTo(18, 22)     # ลากเฉียงตรงขึ้นไปที่ผิวบนสุด (รัศมีปากแก้ว 18 มม.) สร้างผิวด้านข้างเรียบ
    .lineTo(0, 22)      # ลากกลับมาที่แกนกลางเพื่อปิดรูปทรง
    .close()
)

# 3. หมุนเส้นขอบให้เป็นรูปทรงเนื้อตัน 360 องศา (เพื่อเตรียมไปเจาะ)
cavity_solid = cavity_profile.revolve(360, (0, 0), (0, 1))

# 4. เจาะหลุม (Boolean Cut)
# เอาก้อนทรงแก้วไปตัดเนื้อออกจากโมลครึ่งก้อน ผลลัพธ์ที่ได้คือโมลที่มีหลุมโหว่ให้เห็นหน้าตัดชัดเจน
final_mold = mold.cut(cavity_solid)

# 5. บันทึกผลลัพธ์ออกเป็นไฟล์ .step
filename = "Half_Mold_Profile_Measurable.step"
cq.exporters.export(final_mold, filename)

print(f"เสร็จสิ้น! บันทึกไฟล์ 3D แม่พิมพ์สำหรับวัดโปรเจคชั่นไว้ที่: {filename}")